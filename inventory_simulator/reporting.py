"""CSV and text report generation."""

import csv
from pathlib import Path
from typing import Iterable


def write_csv(path: Path, rows: Iterable[dict]) -> None:
    materialized = list(rows)
    path.parent.mkdir(parents=True, exist_ok=True)
    if not materialized:
        path.write_text("", encoding="utf-8")
        return
    with path.open("w", newline="", encoding="utf-8") as stream:
        writer = csv.DictWriter(stream, fieldnames=list(materialized[0]))
        writer.writeheader()
        writer.writerows(materialized)


def write_report(path: Path, summaries: list[dict], config_path: Path, extension: str) -> None:
    lines = ["Inventory and Profitability Simulator", f"Configuration: {config_path}",
        f"Selected extension: {extension or 'core only'}", "",
        "Operating result is gross profit minus holding and ordering costs.",
        "Historical sales are treated as demand because the model assumes no historical stockouts.",
        "Unmet demand is permanently lost. Demand is generated by a Poisson model using each product's historical daily mean.",
        "All policy and storage comparisons share the same demand array.",
        "Orders arrive the next morning. Final-day orders are charged and reported as outstanding, separate from on-hand stock.", ""]
    ordered = sorted(summaries, key=lambda row: (row["policy"], row["allocation_rule"]))
    best = max(ordered, key=lambda row: row["operating_result"])
    lines.append("Scenario comparison")
    for row in ordered:
        fulfilment = row["fulfilment_rate"] if isinstance(row["fulfilment_rate"], str) else f"{row['fulfilment_rate']:.2%}"
        lines.append(f"{row['policy']} / {row['allocation_rule']}: operating result EUR {row['operating_result']:.2f}; "
            f"fulfilment {fulfilment}; "
            f"lost sales {int(row['lost_sales'])}; final stock {int(row['final_stock'])}; outstanding orders {int(row['outstanding_orders'])}.")
    lines += ["", f"Recommendation: under this simulated demand, {best['policy']} with {best['allocation_rule']} produced the highest operating result. "
        "Treat this as a scenario result, not a forecast or causal conclusion.", "", "Limitations", 
        "- Poisson demand assumes independent daily counts and a stable historical mean.",
        "- Historical sales equal demand; real stockouts could make this estimate too low.",
        "- Prices, purchase costs, lead time and costs are simplified and held fixed.",
        "- The 60-day simulation is one seeded scenario; it does not quantify uncertainty across many seeds."]
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
